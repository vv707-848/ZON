def _over(price: float, top: float | None, strict: bool) -> bool:
    return top is not None and price > (top if strict else top * 1.10)


def grade_offer(offer: Offer, need: dict[str, Any], wishes: dict[str, str], strict: bool) -> int:
    _, price, bedrooms, _, has, breaks = offer
    if _over(price, need.get("budget_max"), strict):
        return 0
    if need.get("bedrooms") and (bedrooms is None or bedrooms < need["bedrooms"]):
        return 0
    if any(kind == "must" and key in breaks for key, kind in wishes.items()):
        return 0
    share = sum(key in has for key in wishes) / len(wishes) if wishes else 1.0
    grade = 3 if share == 1 else 2 if share >= 0.5 else 1
    if need.get("budget_max") and price > need["budget_max"]:
        grade = max(1, grade - 1)
    return grade


