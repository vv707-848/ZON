"""Writes backend/app/Support/Site/Icons.php from the app's Lucide set (app/lib/core/icons/lucide_data.dart).

The website draws the same icons as the app, from the same geometry: run this after adding an icon to the app.

    python3 -I _tools/site_icons.py app/lib/core/icons/lucide_data.dart backend/app/Support/Site/Icons.php
"""

import re
import sys

SHAPE = re.compile(r"LucideShape\.(path|circle|ellipse|rect|line|poly)\((.*?)\),\s*$", re.S)


def number(text: str) -> str:
    value = float(text)
    return str(int(value)) if value.is_integer() else str(value)


def svg(kind: str, args: str) -> str:
    if kind == "path":
        d = re.search(r"'([^']*)'", args)
        return f'<path d="{d.group(1)}"/>'
    if kind == "poly":
        points = [number(p) for p in re.search(r"\[(.*?)\]", args).group(1).split(",") if p.strip()]
        pairs = " ".join(f"{points[i]},{points[i + 1]}" for i in range(0, len(points), 2))
        tag = "polygon" if "closed: true" in args else "polyline"
        return f'<{tag} points="{pairs}"/>'
    values = [number(v) for v in args.split(",")]
    if kind == "circle":
        return f'<circle cx="{values[0]}" cy="{values[1]}" r="{values[2]}"/>'
    if kind == "ellipse":
        return f'<ellipse cx="{values[0]}" cy="{values[1]}" rx="{values[2]}" ry="{values[3]}"/>'
    if kind == "rect":
        return f'<rect x="{values[0]}" y="{values[1]}" width="{values[2]}" height="{values[3]}" rx="{values[4]}" ry="{values[5]}"/>'
    return f'<line x1="{values[0]}" y1="{values[1]}" x2="{values[2]}" y2="{values[3]}"/>'


def main(source: str, target: str) -> None:
    text = open(source, encoding="utf-8").read()
    icons: dict[str, list[str]] = {}
    for block in re.finditer(r"^  '([A-Za-z0-9]+)': <LucideShape>\[(.*?)^  \],", text, re.S | re.M):
        name, body = block.group(1), block.group(2)
        shapes = []
        for item in re.split(r"\n(?=\s*LucideShape\.)", body):
            item = re.sub(r"//[^\n]*", "", item).strip()
            if not item:
                continue
            match = SHAPE.match(item if item.endswith(",") else item + ",")
            if match is None:
                raise SystemExit(f"{name}: cannot read {item!r}")
            shapes.append(svg(match.group(1), " ".join(match.group(2).split())))
        icons[name] = shapes
    if len(icons) < 50:
        raise SystemExit(f"only {len(icons)} icons read from {source}")

    lines = [
        "<?php",
        "",
        "namespace App\\Support\\Site;",
        "",
        "/**",
        " * The app's Lucide icons (ISC licence) as SVG markup for the website — GENERATED by _tools/site_icons.py from",
        " * app/lib/core/icons/lucide_data.dart; do not edit by hand. Drawn on a 24 × 24 grid with round caps and joins.",
        " */",
        "final class Icons",
        "{",
        "    public const SHAPES = [",
    ]
    for name in sorted(icons):
        inner = "".join(icons[name]).replace("'", "\\'")
        lines.append(f"        '{name}' => '{inner}',")
    lines += [
        "    ];",
        "",
        "    /** An icon as inline SVG: it takes the colour of the text around it (currentColor). */",
        "    public static function svg(string $name, int $size = 20, float $stroke = 1.8, string $class = ''): string",
        "    {",
        "        $shapes = self::SHAPES[$name] ?? throw new \\InvalidArgumentException(\"No icon {$name}\");",
        "        $class = $class === '' ? 'icon' : 'icon '.$class;",
        "",
        "        return '<svg class=\"'.e($class).'\" width=\"'.$size.'\" height=\"'.$size.'\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\"'",
        "            .' stroke-width=\"'.$stroke.'\" stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\" focusable=\"false\">'.$shapes.'</svg>';",
        "    }",
        "}",
        "",
    ]
    open(target, "w", encoding="utf-8").write("\n".join(lines))
    print(f"{len(icons)} icons → {target}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
