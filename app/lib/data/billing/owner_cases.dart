// The owner plan («باقة المالك»): one case per advertised property.
//
// The plan is active only when BOTH are true for a property:
//   1. its brokerage contract (عقد الوساطة) is approved — in production the
//      owner approves it on REGA's site through Nafath and the server checks
//      the approval; and
//   2. its listing is published.
// The steps are kept apart on purpose (form → contract → licence fee →
// licence → published): entering the deed, a locally generated number or a
// simulated payment never counts as an approved contract.
//
// The commission (0.5 % after the sale, see Pricing.ownerCommissionPercent)
// belongs to the property and the contract of its case only.

import 'package:zon/core/utils/clock.dart';
import 'package:zon/data/billing/billing.dart';
import 'package:zon/data/catalog/catalog.dart';
import 'package:zon/data/notifications/notification_center.dart';
import 'package:zon/data/store.dart';

/// Contract status of a case.
abstract final class ContractStatus {
  /// Deed and identity entered; contract sent, waiting for the owner's
  /// approval at REGA (Nafath).
  static const String submitted = 'submitted';

  /// Approval confirmed (server) — or by the development simulation.
  static const String approved = 'approved';
}

/// One property going through the owner path.
class OwnerCase {
  const OwnerCase({
    required this.id,
    required this.createdAt,
    required this.deedNo,
    required this.contractStatus,
    this.contractRef,
    this.approvalSimulated = false,
    this.feePaid = false,
    this.feeRef,
    this.licenceNumber,
    this.licenceSimulated = false,
    this.listingId,
    this.publishedAt,
    this.commissionPercent = Pricing.ownerCommissionPercent,
  });

  final String id;
  final String createdAt;

  /// Deed / property number entered by the owner.
  final String deedNo;

  /// See [ContractStatus].
  final String contractStatus;

  /// Contract reference returned with the approval.
  final String? contractRef;

  /// The approval came from the development simulation, not from REGA.
  final bool approvalSimulated;

  /// The advertising licence fee (Pricing.adLicenceFee) was paid.
  final bool feePaid;
  final String? feeRef;

  /// Advertising licence number of the property.
  final String? licenceNumber;

  /// [licenceNumber] was generated by the simulation (not issued by REGA).
  final bool licenceSimulated;

  /// The published listing of this property.
  final String? listingId;
  final String? publishedAt;

  /// Commission due after the sale of THIS property (locked in its contract).
  final double commissionPercent;

  bool get contractApproved => contractStatus == ContractStatus.approved;
  bool get published => listingId != null;

  /// The step the owner is on.
  String get stage {
    if (!contractApproved) return 'contract';
    if (!feePaid) return 'fee';
    if (licenceNumber == null) return 'licence';
    if (!published) return 'listing';
    return 'active';
  }

  OwnerCase copyWith(Map<String, Object?> patch) => OwnerCase.fromJson(<String, Object?>{...toJson(), ...patch});

  Map<String, Object?> toJson() => <String, Object?>{
    'id': id,
    'createdAt': createdAt,
    'deedNo': deedNo,
    'contractStatus': contractStatus,
    if (contractRef != null) 'contractRef': contractRef,
    'approvalSimulated': approvalSimulated,
    'feePaid': feePaid,
    if (feeRef != null) 'feeRef': feeRef,
    if (licenceNumber != null) 'licenceNumber': licenceNumber,
    'licenceSimulated': licenceSimulated,
    if (listingId != null) 'listingId': listingId,
    if (publishedAt != null) 'publishedAt': publishedAt,
    'commissionPercent': commissionPercent,
  };

  factory OwnerCase.fromJson(Map<String, Object?> j) => OwnerCase(
    id: j['id'] as String? ?? '',
    createdAt: j['createdAt'] as String? ?? '',
    deedNo: j['deedNo'] as String? ?? '',
    contractStatus: j['contractStatus'] as String? ?? ContractStatus.submitted,
    contractRef: j['contractRef'] as String?,
    approvalSimulated: j['approvalSimulated'] == true,
    feePaid: j['feePaid'] == true,
    feeRef: j['feeRef'] as String?,
    licenceNumber: j['licenceNumber'] as String?,
    licenceSimulated: j['licenceSimulated'] == true,
    listingId: j['listingId'] as String?,
    publishedAt: j['publishedAt'] as String?,
    commissionPercent: (numOrNull(j['commissionPercent']) ?? Pricing.ownerCommissionPercent),
  );
}

/// The owner cases of the signed-in account.
final OwnerCases ownerCases = OwnerCases._();

class OwnerCases {
  OwnerCases._();

  static const String _key = 'zon.owner.cases.v1';

  /// The cases of the signed-in account, or of [accountId].
  List<OwnerCase> all({String? accountId}) {
    final raw = store.readAccountJson(_key, accountId: accountId);
    if (raw is! List) return <OwnerCase>[];
    return raw.whereType<Map<String, Object?>>().map(OwnerCase.fromJson).toList();
  }

  void _saveAll(List<OwnerCase> rows, {String? accountId}) =>
      store.writeAccountJson(_key, rows.map((e) => e.toJson()).toList(), accountId: accountId);

  OwnerCase? byId(String id, {String? accountId}) {
    for (final c in all(accountId: accountId)) {
      if (c.id == id) return c;
    }
    return null;
  }

  OwnerCase _update(String id, Map<String, Object?> patch, {String? accountId}) {
    final rows = all(accountId: accountId);
    final i = rows.indexWhere((c) => c.id == id);
    if (i < 0) throw StateError('unknown owner case $id');
    rows[i] = rows[i].copyWith(patch);
    _saveAll(rows, accountId: accountId);
    return rows[i];
  }

  /// Fee payments running now (`<accountId>:<caseId>`), against double taps.
  final Set<String> _paying = <String>{};

  /// The case still in progress (not published yet), newest first.
  OwnerCase? current() {
    final open = all().where((c) => !c.published).toList();
    return open.isEmpty ? null : open.last;
  }

  /// A case whose contract is approved and whose listing is published and
  /// still exists.
  OwnerCase? activeCase() {
    for (final c in all().reversed) {
      if (!c.contractApproved || c.listingId == null) continue;
      final l = store.listingById(c.listingId!);
      if (l != null && l.active != false) return c;
    }
    return null;
  }

  /// Whether «باقة المالك» is active (both conditions met).
  bool planActive() => activeCase() != null;

  /// Step 1 — the owner submitted the deed and identity: the brokerage
  /// contract is sent and waits for approval. Nothing is active yet.
  OwnerCase submitContract({required String deedNo}) {
    final now = appNow();
    final c = OwnerCase(
      id: 'oc-${now.microsecondsSinceEpoch}',
      createdAt: now.toIso8601String(),
      deedNo: deedNo.trim(),
      contractStatus: ContractStatus.submitted,
    );
    _saveAll(<OwnerCase>[...all(), c]);
    return c;
  }

  /// Step 2 — the approval of the contract. In production only the server
  /// sets it, after checking the approval at REGA. Here it is called by the
  /// development simulation (marked [simulated]) and by the tests.
  OwnerCase approveContract(String id, {required String reference, bool simulated = true}) =>
      _update(id, <String, Object?>{'contractStatus': ContractStatus.approved, 'contractRef': reference, 'approvalSimulated': simulated});

  /// Step 3 — pays the advertising licence fee (simulated) once the contract
  /// is approved. The licence is then issued (simulated number).
  ///
  /// The case, the payment and the licence belong to the account that pressed
  /// «ادفع», whichever account is signed in when the answer arrives (QA F02).
  Future<PaymentReceipt> payLicenceFee(String id) async {
    final acc = store.accountId;
    if (acc == null) return const PaymentReceipt(PaymentStatus.failed);
    final c = byId(id, accountId: acc);
    if (c == null || !c.contractApproved) return const PaymentReceipt(PaymentStatus.failed);
    if (c.feePaid) return PaymentReceipt(PaymentStatus.paid, reference: c.feeRef, amount: Pricing.adLicenceFee);
    final key = '$acc:$id';
    if (_paying.contains(key)) return const PaymentReceipt(PaymentStatus.failed);
    _paying.add(key);
    try {
      final rec = billing.beginPayment(acc, 'licence:$id', Pricing.adLicenceFee);
      final receipt = await PaymentSimulator.charge(amount: Pricing.adLicenceFee, purpose: 'licence:$id');
      billing.endPayment(acc, rec, receipt);
      if (!receipt.ok) return receipt;
      final n = '72${(appNow().microsecondsSinceEpoch % 100000000).toString().padLeft(8, '0')}';
      _update(id, <String, Object?>{'feePaid': true, 'feeRef': receipt.reference, 'licenceNumber': n, 'licenceSimulated': true}, accountId: acc);
      if (store.accountId != acc) {
        notifications.add(
          kind: NoteKind.plan,
          title: 'دُفعت رسوم الترخيص الإعلاني',
          body: 'أكمل تفاصيل عرضك ثم انشره.',
          target: '/add?type=listing',
          key: 'paid:${rec.id}',
          accountId: acc,
        );
      }
      return receipt;
    } finally {
      _paying.remove(key);
    }
  }

  /// Step 4 — the listing of the case is published: the plan is active.
  OwnerCase markPublished(String id, String listingId) {
    final c = _update(id, <String, Object?>{'listingId': listingId, 'publishedAt': appNow().toIso8601String()});
    if (c.contractApproved) {
      notifications.add(
        kind: NoteKind.plan,
        title: 'باقة المالك مفعّلة',
        body: 'عقد الوساطة موثّق وعرضك منشور — ${Pricing.ownerCommissionPercent}٪ سعي بعد بيع هذا العقار.',
        target: '/account/plans',
        key: 'owner-active:$id',
      );
    }
    return c;
  }
}
